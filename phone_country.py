def get_country_by_phone(phone: str) -> str:
    """Detect country from phone number using calling code prefix.
    
    Args:
        phone: Phone number without '+' prefix.
        
    Returns:
        Country name or 'Unknown'.
    """
    phone = phone.lstrip("+").strip()
    # Try longest prefix first (4 digits, then 3, 2, 1)
    for length in (4, 3, 2, 1):
        prefix = phone[:length]
        if prefix in COUNTRY_CODES:
            return COUNTRY_CODES[prefix]
    return "Unknown"
